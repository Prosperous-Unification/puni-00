for (const field of ['sourcePath', 'snapshotPath'] as const) {
  for (const state of ['missing', 'unreadable'] as const) {
    test('names ' + field + ' when its actual generated-report file is ' + state, async () => {
      const paths = await fixture();
      const filesystem = await import('node:fs');
      if (state === 'missing') filesystem.unlinkSync(paths[field]);
      else filesystem.chmodSync(paths[field], 0);
      try {
        const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
          '--report=' + paths.reportPath,
        ]);
        expect(verified.exitCode).not.toBe(0);
        expect(verified.stderr).toContain(field);
        if (state === 'missing') expect(existsSync(paths[field])).toBe(false);
      } finally {
        if (state === 'unreadable') filesystem.chmodSync(paths[field], 0o600);
      }
    });
  }
}

test('refuses nonempty snapshot sidecar evidence before opening snapshot SQLite', async () => {
  const paths = await fixture();
  const walPath = paths.snapshotPath + '-wal';
  const marker = Buffer.from('deliberate nonempty sidecar evidence; not an ordinary WAL writer');
  writeFileSync(walPath, marker);
  const snapshotBefore = readFileSync(paths.snapshotPath);
  const sourceBefore = readFileSync(paths.sourcePath);
  const reportBefore = readFileSync(paths.reportPath);
  const { createHash } = await import('node:crypto');
  expect(createHash('sha256').update(snapshotBefore).digest('hex')).toBe(
    paths.report.snapshotSha256,
  );
  const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
    '--report=' + paths.reportPath,
  ]);
  expect(verified.exitCode).not.toBe(0);
  expect(verified.stderr).toContain('snapshot -wal');
  expect(readFileSync(walPath)).toEqual(marker);
  expect(readFileSync(paths.snapshotPath)).toEqual(snapshotBefore);
  expect(readFileSync(paths.sourcePath)).toEqual(sourceBefore);
  expect(readFileSync(paths.reportPath)).toEqual(reportBefore);
});

test('verifies a WAL-header report with absent source sidecars and denied artifact writes', async () => {
  const paths = await fixture();
  const filesystem = await import('node:fs');
  const parent = dirname(paths.sourcePath);
  filesystem.chmodSync(paths.sourcePath, 0o400);
  filesystem.chmodSync(paths.snapshotPath, 0o400);
  filesystem.chmodSync(paths.reportPath, 0o400);
  const header = readFileSync(paths.sourcePath);
  expect([header[18], header[19]]).toEqual([2, 2]);
  if (existsSync(paths.sourcePath + '-wal')) {
    expect(filesystem.statSync(paths.sourcePath + '-wal').size).toBe(0);
    filesystem.unlinkSync(paths.sourcePath + '-wal');
  }
  if (existsSync(paths.sourcePath + '-shm')) filesystem.unlinkSync(paths.sourcePath + '-shm');
  expect(existsSync(paths.sourcePath + '-wal')).toBe(false);
  expect(existsSync(paths.sourcePath + '-shm')).toBe(false);
  filesystem.chmodSync(parent, 0o500);
  try {
    expect(() => {
      writeFileSync(join(parent, 'write-denial-control'), 'must not be written');
    }).toThrow(/EACCES/);
    const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
      '--report=' + paths.reportPath,
    ]);
    expect(verified.stderr).toBe('');
    expect(verified.exitCode).toBe(0);
    expect(JSON.parse(verified.stdout)).toEqual(paths.report);
  } finally {
    filesystem.chmodSync(parent, 0o700);
    filesystem.chmodSync(paths.sourcePath, 0o600);
    filesystem.chmodSync(paths.snapshotPath, 0o600);
    filesystem.chmodSync(paths.reportPath, 0o600);
  }
});

