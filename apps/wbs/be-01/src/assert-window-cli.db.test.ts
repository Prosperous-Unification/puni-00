for (const field of [
  'version',
  'sourcePath',
  'sourceSha256',
  'sourceBytes',
  'snapshotSha256',
  'snapshotBytes',
  'migrations',
] as const) {
  test('refuses a generated report with changed ' + field + ' and names the field', async () => {
    const paths = await fixture();
    const changed = { ...paths.report };
    if (field === 'version') Object.assign(changed, { version: 2 });
    if (field === 'sourcePath') changed.sourcePath = join(dirname(paths.sourcePath), 'another.db');
    if (field === 'sourceSha256' || field === 'snapshotSha256') changed[field] = '0'.repeat(64);
    if (field === 'sourceBytes' || field === 'snapshotBytes') changed[field] += 1;
    if (field === 'migrations') changed.migrations = paths.report.migrations.slice(1);
    writeFileSync(paths.reportPath, JSON.stringify(changed));
    const sourceBefore = readFileSync(paths.sourcePath);
    const snapshotBefore = readFileSync(paths.snapshotPath);
    const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
      '--report=' + paths.reportPath,
    ]);
    expect(verified.exitCode).not.toBe(0);
    expect(verified.stderr).toContain(field);
    expect(readFileSync(paths.sourcePath)).toEqual(sourceBefore);
    expect(readFileSync(paths.snapshotPath)).toEqual(snapshotBefore);
  });
}

