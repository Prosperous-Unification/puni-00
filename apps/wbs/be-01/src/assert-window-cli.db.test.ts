import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { openDatabase } from '@wbs/store-sqlite/db';
import { runMigrations } from '@wbs/store-sqlite/migrate';
import { copyRecoveryPrefix } from '@wbs/store-sqlite/testing/recovery-state';
import type { WindowBackupReport } from '@wbs/store-sqlite/window-backup';
import { afterEach, expect, test } from 'bun:test';

const APP_ROOT = dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

async function invoke(file: string, sourcePath: string, args: readonly string[]) {
  const child = Bun.spawn([process.execPath, 'run', 'src/' + file, ...args], {
    cwd: APP_ROOT,
    env: { ...process.env, DB_PATH: sourcePath },
    stdout: 'pipe',
    stderr: 'pipe',
    signal: AbortSignal.timeout(3500),
    killSignal: 'SIGKILL',
  });
  const [exitCode, stdout, stderr] = await Promise.all([
    child.exited,
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
  ]);
  return { exitCode, stdout, stderr };
}

async function fixture(sourceName = 'source.db') {
  const root = mkdtempSync(join(tmpdir(), 'wbs-assert-window-'));
  roots.push(root);
  const sourcePath = join(root, sourceName);
  const snapshotPath = join(root, 'snapshot.db');
  const reportPath = join(root, 'report.json');
  const migrations = copyRecoveryPrefix(root, '20261115120000_add_step_migration_report');
  runMigrations(sourcePath, migrations);
  const writer = openDatabase(sourcePath);
  try {
    writer.run('CREATE TABLE window_verification_marker (value TEXT NOT NULL)');
  } finally {
    writer.close();
  }
  const generated = await invoke('backup-db-cli.ts', sourcePath, [
    snapshotPath,
    '--report=' + reportPath,
  ]);
  expect(generated.exitCode).toBe(0);
  const report = JSON.parse(readFileSync(reportPath, 'utf8')) as WindowBackupReport;
  return { sourcePath, snapshotPath, reportPath, report };
}

test('verifies an unchanged report generated by the actual backup CLI', async () => {
  const paths = await fixture();
  const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
    '--report=' + paths.reportPath,
  ]);
  expect(verified.exitCode).toBe(0);
  expect(JSON.parse(verified.stdout)).toEqual(paths.report);
});

test('refuses a WAL-only source write without checkpointing or changing the WAL evidence', async () => {
  const paths = await fixture();
  const writer = openDatabase(paths.sourcePath);
  writer.run('PRAGMA wal_autocheckpoint=0');
  writer.run("INSERT INTO window_verification_marker VALUES ('uncheckpointed')");
  const walPath = paths.sourcePath + '-wal';
  const before = readFileSync(walPath);
  expect(before.length).toBeGreaterThan(0);
  try {
    const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
      '--report=' + paths.reportPath,
    ]);
    expect(verified.exitCode).not.toBe(0);
    expect(verified.stderr).toContain('source -wal');
    expect(readFileSync(walPath)).toEqual(before);
  } finally {
    writer.close();
  }
});

