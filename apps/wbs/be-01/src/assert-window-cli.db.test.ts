for (const state of [
  'malformed-json',
  'empty',
  'unreadable',
  'directory',
  'fifo',
  'dangling-symlink',
] as const) {
  test('refuses ' + state + ' reportPath without changing source or snapshot', async () => {
    const paths = await fixture();
    const filesystem = await import('node:fs');
    const sourceBefore = readFileSync(paths.sourcePath);
    const snapshotBefore = readFileSync(paths.snapshotPath);
    if (state === 'malformed-json') writeFileSync(paths.reportPath, '{ definitely malformed');
    if (state === 'empty') writeFileSync(paths.reportPath, '');
    if (state === 'unreadable') filesystem.chmodSync(paths.reportPath, 0);
    if (state === 'directory' || state === 'fifo' || state === 'dangling-symlink') {
      filesystem.unlinkSync(paths.reportPath);
      if (state === 'directory') filesystem.mkdirSync(paths.reportPath);
      if (state === 'dangling-symlink')
        filesystem.symlinkSync(join(dirname(paths.reportPath), 'absent.json'), paths.reportPath);
      if (state === 'fifo') expect(Bun.spawnSync(['mkfifo', paths.reportPath]).exitCode).toBe(0);
    }
    try {
      const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
        '--report=' + paths.reportPath,
      ]);
      expect(verified.exitCode).not.toBe(0);
      const refusal =
        state === 'malformed-json' || state === 'empty'
          ? 'reportPath is malformed JSON'
          : state === 'directory' || state === 'fifo'
            ? 'reportPath is not a readable regular file'
            : 'reportPath cannot be opened';
      expect(verified.stderr).toContain('error: ' + refusal);
      expect(readFileSync(paths.sourcePath)).toEqual(sourceBefore);
      expect(readFileSync(paths.snapshotPath)).toEqual(snapshotBefore);
    } finally {
      if (state === 'unreadable') filesystem.chmodSync(paths.reportPath, 0o600);
    }
  });
}

for (const mutation of [
  'duplicate-ledger',
  'empty-ledger',
  'ledger-hash',
  'valid-ledger-hash-mismatch',
  'valid-ledger-name-mismatch',
  'unknown-field',
] as const) {
  test('refuses a generated report with ' + mutation + ' at its external boundary', async () => {
    const paths = await fixture();
    const changed = JSON.parse(readFileSync(paths.reportPath, 'utf8')) as Record<string, unknown>;
    if (mutation === 'duplicate-ledger')
      changed['migrations'] = [...paths.report.migrations, paths.report.migrations[0]];
    if (mutation === 'empty-ledger') changed['migrations'] = [];
    if (mutation === 'ledger-hash')
      changed['migrations'] = [
        { ...paths.report.migrations[0], hash: 'broken' },
        ...paths.report.migrations.slice(1),
      ];
    if (mutation === 'valid-ledger-hash-mismatch' || mutation === 'valid-ledger-name-mismatch')
      changed['migrations'] = paths.report.migrations.map((entry, index) =>
        index === 0
          ? {
              ...entry,
              ...(mutation === 'valid-ledger-hash-mismatch'
                ? { hash: '0'.repeat(64) }
                : { name: 'unapplied-shaped-migration' }),
            }
          : entry,
      );
    if (mutation === 'unknown-field') changed['unexpected'] = 'not accepted';
    writeFileSync(paths.reportPath, JSON.stringify(changed));
    const verified = await invoke('assert-window-cli.ts', paths.sourcePath, [
      '--report=' + paths.reportPath,
    ]);
    expect(verified.exitCode).not.toBe(0);
    expect(verified.stderr).toContain(mutation === 'unknown-field' ? 'unexpected' : 'migrations');
  });
}
